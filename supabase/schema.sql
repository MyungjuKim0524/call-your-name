-- 별빛 방명록(guestbook) 운영 스키마
-- Supabase 대시보드 → SQL Editor에서 실행합니다.

-- 0. 초기화 (처음 설정할 때만 사용)
-- ⚠️ 아래 줄은 기존 방명록 데이터를 모두 삭제합니다. 운영 중인 DB에서는 실행하지 마세요.
-- drop table if exists public.guestbook cascade;

-- 1. 테이블 생성
create table public.guestbook (
  id bigint generated by default as identity primary key,
  author text not null default '친구',
  badge text not null default '✉️',
  message text not null check (char_length(message) between 1 and 60),
  created_at timestamptz not null default now()
);

-- 2. 행 단위 보안(RLS) 활성화
alter table public.guestbook enable row level security;

-- 3. 조회(SELECT) 정책: 비로그인(anon)·로그인 사용자 모두 읽기 허용
create policy "guestbook_select_all"
  on public.guestbook for select
  to anon, authenticated
  using (true);

-- 4. 등록(INSERT) 정책: 비로그인(anon)·로그인 사용자 모두 작성 허용
create policy "guestbook_insert_all"
  on public.guestbook for insert
  to anon, authenticated
  with check (true);

-- 5. 최소 권한 부여: SELECT, INSERT만 허용하고 UPDATE, DELETE는 부여하지 않아 차단
grant usage on schema public to anon, authenticated;
grant select, insert on table public.guestbook to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
